package com.galithin.web.sources.catalog

import com.galithin.web.domain.AssetReference
import com.galithin.web.domain.CatalogEntry
import com.galithin.web.domain.CatalogKind
import com.galithin.web.domain.CatalogManifest
import com.galithin.web.domain.GuildCatalog
import com.galithin.web.domain.RichText
import java.nio.file.Files
import java.nio.file.Path
import java.security.MessageDigest
import java.time.Duration
import kotlinx.serialization.builtins.ListSerializer
import kotlinx.serialization.encodeToString
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonPrimitive
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import kotlin.test.assertEquals
import kotlin.test.assertTrue

class FileCatalogRepositoryTest {
    @TempDir
    lateinit var bundle: Path

    @Test
    fun `loads Kotlinx metadata values generated by content tooling`() {
        val catalogDirectory = bundle.resolve("catalog")
        Files.createDirectories(catalogDirectory)
        val itemsPath = catalogDirectory.resolve("items.json")
        val entry = CatalogEntry(
            id = "test_sword",
            kind = CatalogKind.ITEMS,
            name = RichText("{\"text\":\"Test Sword\"}", "Test Sword", "Test Sword"),
            metadata = mapOf(
                "material" to JsonPrimitive("minecraft:diamond_sword"),
                "customModelData" to JsonPrimitive(42),
                "enabled" to JsonPrimitive(true),
            ),
            assets = AssetReference(
                catalogVersion = "test-version",
                modelUrl = null,
                equipmentUrl = "/assets/test-version/assets/nexo/equipment/test.json",
            ),
        )
        Files.writeString(
            itemsPath,
            JSON.encodeToString(ListSerializer(CatalogEntry.serializer()), listOf(entry)),
        )
        val guildsPath = writeGuildCatalog()
        val relativeItems = "catalog/items.json"
        val manifest = CatalogManifest(
            schemaVersion = 1,
            catalogVersion = "test-version",
            createdAt = "2026-08-09T00:00:00Z",
            files = mapOf(
                relativeItems to sha256(itemsPath),
                "catalog/guilds.json" to sha256(guildsPath),
            ),
        )
        Files.writeString(bundle.resolve("manifest.json"), JSON.encodeToString(manifest))

        FileCatalogRepository(bundle, Duration.ofHours(1)).use { repository ->
            assertTrue(repository.ready())
            assertEquals("test-version", repository.version())
            assertEquals(1_000, repository.guilds().baseExperienceCost)
            val loaded = repository.entry(CatalogKind.ITEMS, "test_sword")
            assertEquals("minecraft:diamond_sword", loaded?.metadata?.get("material")?.let { (it as JsonPrimitive).content })
            assertEquals(42, (loaded?.metadata?.get("customModelData") as JsonPrimitive).content.toInt())
            assertEquals(true, (loaded.metadata["enabled"] as JsonPrimitive).content.toBoolean())
            assertEquals(
                "/assets/test-version/assets/nexo/equipment/test.json",
                loaded.assets?.equipmentUrl,
            )
        }
    }

    @Test
    fun `loads Nexo space advances into the glyph registry`() {
        val shiftPath = bundle.resolve("assets/nexo/font/shift.json")
        Files.createDirectories(shiftPath.parent)
        Files.writeString(
            shiftPath,
            """{"providers":[{"type":"space","advances":{"\uE103":-4,"\uE114":4}}]}""",
        )
        val guildsPath = writeGuildCatalog()
        val relativeShift = "assets/nexo/font/shift.json"
        val manifest = CatalogManifest(
            schemaVersion = 1,
            catalogVersion = "test-version",
            createdAt = "2026-08-09T00:00:00Z",
            files = mapOf(
                relativeShift to sha256(shiftPath),
                "catalog/guilds.json" to sha256(guildsPath),
            ),
        )
        Files.writeString(bundle.resolve("manifest.json"), JSON.encodeToString(manifest))

        FileCatalogRepository(bundle, Duration.ofHours(1)).use { repository ->
            assertEquals(-4, repository.glyphRegistry().shift(0xE103))
            assertEquals(4, repository.glyphRegistry().shift(0xE114))
        }
    }

    private fun sha256(path: Path): String =
        MessageDigest.getInstance("SHA-256")
            .digest(Files.readAllBytes(path))
            .joinToString("") { "%02x".format(it) }

    private fun writeGuildCatalog(): Path {
        val path = bundle.resolve("catalog/guilds.json")
        Files.createDirectories(path.parent)
        Files.writeString(
            path,
            JSON.encodeToString(
                GuildCatalog.serializer(),
                GuildCatalog(1_000, 1.15, 100),
            ),
        )
        return path
    }

    companion object {
        private val JSON = Json { prettyPrint = true; encodeDefaults = true }
    }
}
